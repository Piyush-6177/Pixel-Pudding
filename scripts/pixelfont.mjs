/** width in cells of a string (5px glyphs + 1px gap) */
export const textWidth = (s) => s.length * 6 - 1;
/** Draw text at scale S. Returns width in pixels. */
export function drawText(c, text, x, y, S, color, shadow) {
  let cx = x;
  for (const ch of text.toUpperCase()) {
    const g = GLYPHS[ch] || GLYPHS[' '];
    g.forEach((row, j) => {
      for (let i = 0; i < 5; i++)
        if (row[i] === '#') {
          if (shadow) c.rect(cx + i * S + S, y + j * S + S, S, S, shadow);
          c.rect(cx + i * S, y + j * S, S, S, color);
        }
    });
    cx += 6 * S;
  }
  return cx - x - S;
}
/** Word-wrap to maxChars per line */
export function wrap(text, maxChars) {
  const words = text.split(' ');
  const lines = [];
  let line = '';
  for (const w of words) {
    if ((line + ' ' + w).trim().length > maxChars && line) {
      lines.push(line);
      line = w;
    } else line = (line + ' ' + w).trim();
  }
  if (line) lines.push(line);
  return lines;
}
